use std::collections::HashSet;
use std::fs;
use std::path::Path;

pub const MANAGED_START_MARKER: &str = "# --- SlashNote Managed Start ---";
pub const MANAGED_END_MARKER: &str = "# --- SlashNote Managed End ---";

pub const DEFAULT_VIDEO_EXTS: &[&str] = &[
    "mp4", "mkv", "mov", "avi", "webm", "wmv", "flv", "mpeg", "mpg", "m4v",
];

pub const DEFAULT_AUDIO_EXTS: &[&str] = &[
    "mp3", "wav", "flac", "aac", "ogg", "opus", "m4a", "wma", "aiff",
];

pub const DEFAULT_ARCHIVE_EXTS: &[&str] = &[
    "zip", "rar", "7z", "tar", "gz", "bz2",
];

pub const DEFAULT_BINARY_EXTS: &[&str] = &[
    "exe", "dll", "so", "dylib", "apk", "dmg", "iso",
];

pub const DEFAULT_SYSTEM_PATTERNS: &[&str] = &[
    ".DS_Store",
    "Thumbs.db",
    "*.tmp",
    "*.swp",
    "*~",
    ".trash/",
];

/// Get all default extensions with leading dot, e.g. `[".mp4", ".mkv", ...]`.
pub fn get_default_extensions() -> Vec<String> {
    let mut exts = Vec::new();
    for list in [
        DEFAULT_VIDEO_EXTS,
        DEFAULT_AUDIO_EXTS,
        DEFAULT_ARCHIVE_EXTS,
        DEFAULT_BINARY_EXTS,
    ] {
        for ext in list {
            exts.push(format!(".{}", ext));
        }
    }
    exts
}

/// Normalize an extension string (e.g. "mp4", ".MP4", "*.mov" -> ".mp4").
/// Returns Err if the extension is markdown (.md / .markdown) or invalid.
pub fn normalize_extension(raw: &str) -> Result<String, String> {
    let trimmed = raw.trim();
    if trimmed.is_empty() {
        return Err("Extension cannot be empty".to_string());
    }

    // Strip leading wildcards like *. or *
    let stripped = trimmed.trim_start_matches('*');
    let ext_without_dot = stripped.trim_start_matches('.');

    if ext_without_dot.is_empty() {
        return Err("Invalid extension format".to_string());
    }

    let lower = ext_without_dot.to_lowercase();

    // Markdown notes must never be ignored
    if lower == "md" || lower == "markdown" {
        return Err("Markdown notes (.md, .markdown) cannot be ignored".to_string());
    }

    // Check for invalid characters (no slashes, wildcards, spaces, or control characters)
    for c in lower.chars() {
        if !c.is_alphanumeric() && c != '.' && c != '_' && c != '-' {
            return Err(format!("Extension contains invalid character: '{}'", c));
        }
    }

    Ok(format!(".{}", lower))
}

/// Parse a comma- or space-separated list of extensions, normalize, and deduplicate.
pub fn parse_and_normalize_list(input: &str) -> Result<Vec<String>, String> {
    let mut result = Vec::new();
    let mut seen = HashSet::new();

    for token in input.split(|c: char| c == ',' || c.is_whitespace()) {
        let token = token.trim();
        if token.is_empty() {
            continue;
        }
        let normalized = normalize_extension(token)?;
        if seen.insert(normalized.clone()) {
            result.push(normalized);
        }
    }

    Ok(result)
}

/// Generate the managed block content for `.gitignore`.
pub fn generate_managed_block(extensions: &[String]) -> String {
    let mut block = String::new();
    block.push_str(MANAGED_START_MARKER);
    block.push('\n');
    block.push_str("# Automatically generated by SlashNote. User rules outside this block are preserved.\n");
    block.push_str("\n# Operating system & temporary files\n");
    for pattern in DEFAULT_SYSTEM_PATTERNS {
        block.push_str(pattern);
        block.push('\n');
    }

    block.push_str("\n# Ignored file types\n");
    let mut seen = HashSet::new();
    for ext in extensions {
        let trimmed = ext.trim().trim_start_matches('*');
        let norm = if trimmed.starts_with('.') {
            trimmed.to_lowercase()
        } else {
            format!(".{}", trimmed.to_lowercase())
        };

        if norm == ".md" || norm == ".markdown" {
            continue;
        }

        if seen.insert(norm.clone()) {
            block.push_str(&format!("*{}", norm));
            block.push('\n');
        }
    }

    block.push_str(MANAGED_END_MARKER);
    block.push('\n');
    block
}

/// Update `.gitignore` text by replacing or inserting the managed block,
/// strictly preserving any user-defined lines before or after.
pub fn update_gitignore_content(existing_content: &str, extensions: &[String]) -> String {
    let managed_block = generate_managed_block(extensions);

    if let Some(start_idx) = existing_content.find(MANAGED_START_MARKER) {
        let before = &existing_content[..start_idx];
        if let Some(end_offset) = existing_content[start_idx..].find(MANAGED_END_MARKER) {
            let after_idx = start_idx + end_offset + MANAGED_END_MARKER.len();
            // Consume optional trailing newline from the marker line
            let rest = &existing_content[after_idx..];
            let after = if let Some(stripped) = rest.strip_prefix("\r\n") {
                stripped
            } else if let Some(stripped) = rest.strip_prefix('\n') {
                stripped
            } else {
                rest
            };

            let mut out = before.to_string();
            out.push_str(&managed_block);
            out.push_str(after);
            out
        } else {
            // Start marker found but no end marker; replace to end of string
            let mut out = before.to_string();
            out.push_str(&managed_block);
            out
        }
    } else {
        // No managed block exists yet; append to existing content
        let trimmed_existing = existing_content.trim_end();
        if trimmed_existing.is_empty() {
            managed_block
        } else {
            format!("{}\n\n{}", trimmed_existing, managed_block)
        }
    }
}

/// Synchronize the vault's `.gitignore` file with the given extensions.
/// Preserves existing user rules outside the SlashNote managed block.
/// Only writes if changes are detected.
pub fn sync_gitignore_file(vault_path: &Path, extensions: &[String]) -> Result<(), String> {
    if !vault_path.exists() {
        return Err(format!("Vault path does not exist: {}", vault_path.display()));
    }

    let gitignore_path = vault_path.join(".gitignore");
    let existing_content = if gitignore_path.exists() {
        fs::read_to_string(&gitignore_path).map_err(|e| format!("Failed to read .gitignore: {}", e))?
    } else {
        String::new()
    };

    let updated_content = update_gitignore_content(&existing_content, extensions);

    if existing_content != updated_content {
        fs::write(&gitignore_path, updated_content)
            .map_err(|e| format!("Failed to write .gitignore: {}", e))?;
    }

    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_default_extensions() {
        let defaults = get_default_extensions();
        assert!(defaults.contains(&".mp4".to_string()));
        assert!(defaults.contains(&".mp3".to_string()));
        assert!(defaults.contains(&".zip".to_string()));
        assert!(defaults.contains(&".exe".to_string()));
        assert_eq!(defaults.len(), 32);
    }

    #[test]
    fn test_normalize_extension() {
        assert_eq!(normalize_extension("mp4").unwrap(), ".mp4");
        assert_eq!(normalize_extension(".mkv").unwrap(), ".mkv");
        assert_eq!(normalize_extension("*.MOV").unwrap(), ".mov");
        assert_eq!(normalize_extension("tar.gz").unwrap(), ".tar.gz");

        // Rejection
        assert!(normalize_extension("md").is_err());
        assert!(normalize_extension(".markdown").is_err());
        assert!(normalize_extension("").is_err());
        assert!(normalize_extension("../etc").is_err());
        assert!(normalize_extension("bad/name").is_err());
    }

    #[test]
    fn test_parse_and_normalize_list() {
        let input = "mp4, .mkv, *.avi   mov, .mp4";
        let res = parse_and_normalize_list(input).unwrap();
        assert_eq!(res, vec![".mp4", ".mkv", ".avi", ".mov"]);
    }

    #[test]
    fn test_gitignore_creation_and_preservation() {
        let exts = vec![".mp4".to_string(), ".zip".to_string()];
        let created = update_gitignore_content("", &exts);
        assert!(created.contains(MANAGED_START_MARKER));
        assert!(created.contains("*.mp4"));
        assert!(created.contains("*.zip"));
        assert!(created.contains(MANAGED_END_MARKER));

        // Test preserving user rules before and after
        let user_content = format!(
            "# Custom user header\nmy-secrets/\n\n{}\n# Custom user footer\n*.log\n",
            created
        );

        let new_exts = vec![".mp4".to_string(), ".mkv".to_string()];
        let updated = update_gitignore_content(&user_content, &new_exts);

        assert!(updated.starts_with("# Custom user header\nmy-secrets/\n\n"));
        assert!(updated.ends_with("# Custom user footer\n*.log\n"));
        assert!(updated.contains("*.mkv"));
        assert!(!updated.contains("*.zip"));
    }

    #[test]
    fn test_sync_gitignore_file_idempotency() {
        let temp_dir = std::env::temp_dir().join(format!("slashnote_test_{}", std::process::id()));
        let _ = fs::create_dir_all(&temp_dir);

        let initial_user_content = "# My rules\nsecret.env\n";
        let gitignore_path = temp_dir.join(".gitignore");
        fs::write(&gitignore_path, initial_user_content).unwrap();

        let exts = vec![".mp4".to_string(), ".pdf".to_string()];
        sync_gitignore_file(&temp_dir, &exts).unwrap();

        let content_pass1 = fs::read_to_string(&gitignore_path).unwrap();
        assert!(content_pass1.starts_with("# My rules\nsecret.env\n"));
        assert!(content_pass1.contains("*.mp4"));
        assert!(content_pass1.contains("*.pdf"));
        assert!(content_pass1.contains(MANAGED_START_MARKER));
        assert!(content_pass1.contains(MANAGED_END_MARKER));

        // Second pass with same exts should be identical
        sync_gitignore_file(&temp_dir, &exts).unwrap();
        let content_pass2 = fs::read_to_string(&gitignore_path).unwrap();
        assert_eq!(content_pass1, content_pass2);

        // Third pass updating exts
        let new_exts = vec![".docx".to_string()];
        sync_gitignore_file(&temp_dir, &new_exts).unwrap();
        let content_pass3 = fs::read_to_string(&gitignore_path).unwrap();
        assert!(content_pass3.starts_with("# My rules\nsecret.env\n"));
        assert!(content_pass3.contains("*.docx"));
        assert!(!content_pass3.contains("*.mp4"));

        let _ = fs::remove_dir_all(&temp_dir);
    }
}
