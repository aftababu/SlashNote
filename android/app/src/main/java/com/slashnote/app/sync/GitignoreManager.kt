package com.slashnote.app.sync

import java.io.File

object GitignoreManager {
    const val MANAGED_START_MARKER = "# --- SlashNote Managed Start ---"
    const val MANAGED_END_MARKER = "# --- SlashNote Managed End ---"

    val DEFAULT_VIDEO_EXTS = listOf(
        "mp4", "mkv", "mov", "avi", "webm", "wmv", "flv", "mpeg", "mpg", "m4v"
    )

    val DEFAULT_AUDIO_EXTS = listOf(
        "mp3", "wav", "flac", "aac", "ogg", "opus", "m4a", "wma", "aiff"
    )

    val DEFAULT_ARCHIVE_EXTS = listOf(
        "zip", "rar", "7z", "tar", "gz", "bz2"
    )

    val DEFAULT_BINARY_EXTS = listOf(
        "exe", "dll", "so", "dylib", "apk", "dmg", "iso"
    )

    val DEFAULT_SYSTEM_PATTERNS = listOf(
        ".DS_Store",
        "Thumbs.db",
        "*.tmp",
        "*.swp",
        "*~",
        ".trash/"
    )

    fun getDefaultExtensions(): List<String> {
        val all = DEFAULT_VIDEO_EXTS + DEFAULT_AUDIO_EXTS + DEFAULT_ARCHIVE_EXTS + DEFAULT_BINARY_EXTS
        return all.map { ".$it" }
    }

    fun normalizeExtension(raw: String): Result<String> {
        val trimmed = raw.trim()
        if (trimmed.isEmpty()) {
            return Result.failure(IllegalArgumentException("Extension cannot be empty"))
        }

        val stripped = trimmed.trimStart('*').trimStart('.')
        if (stripped.isEmpty()) {
            return Result.failure(IllegalArgumentException("Invalid extension format"))
        }

        val lower = stripped.lowercase()
        if (lower == "md" || lower == "markdown") {
            return Result.failure(IllegalArgumentException("Markdown notes (.md, .markdown) cannot be ignored"))
        }

        for (c in lower) {
            if (!c.isLetterOrDigit() && c != '.' && c != '_' && c != '-') {
                return Result.failure(IllegalArgumentException("Extension contains invalid character: '$c'"))
            }
        }

        return Result.success(".$lower")
    }

    fun parseAndNormalizeList(input: String): Result<List<String>> {
        val result = mutableListOf<String>()
        val seen = mutableSetOf<String>()

        val tokens = input.split(Regex("[,\\s]+"))
        for (token in tokens) {
            val clean = token.trim()
            if (clean.isEmpty()) continue
            val normalized = normalizeExtension(clean).getOrElse { return Result.failure(it) }
            if (seen.add(normalized)) {
                result.add(normalized)
            }
        }

        return Result.success(result)
    }

    fun generateManagedBlock(extensions: List<String>): String {
        val sb = StringBuilder()
        sb.append(MANAGED_START_MARKER).append("\n")
        sb.append("# Automatically generated by SlashNote. User rules outside this block are preserved.\n\n")
        sb.append("# Operating system & temporary files\n")
        for (pattern in DEFAULT_SYSTEM_PATTERNS) {
            sb.append(pattern).append("\n")
        }

        sb.append("\n# Ignored file types\n")
        val seen = mutableSetOf<String>()
        for (ext in extensions) {
            val clean = ext.trim().trimStart('*')
            val norm = if (clean.startsWith('.')) clean.lowercase() else ".${clean.lowercase()}"
            if (norm == ".md" || norm == ".markdown") continue
            if (seen.add(norm)) {
                sb.append("*").append(norm).append("\n")
            }
        }

        sb.append(MANAGED_END_MARKER).append("\n")
        return sb.toString()
    }

    fun updateGitignoreContent(existingContent: String, extensions: List<String>): String {
        val managedBlock = generateManagedBlock(extensions)
        val startIdx = existingContent.indexOf(MANAGED_START_MARKER)

        if (startIdx != -1) {
            val before = existingContent.substring(0, startIdx)
            val endOffset = existingContent.indexOf(MANAGED_END_MARKER, startIdx)
            if (endOffset != -1) {
                val afterIdx = endOffset + MANAGED_END_MARKER.length
                var after = existingContent.substring(afterIdx)
                if (after.startsWith("\r\n")) {
                    after = after.substring(2)
                } else if (after.startsWith("\n")) {
                    after = after.substring(1)
                }
                return before + managedBlock + after
            } else {
                return before + managedBlock
            }
        } else {
            val trimmed = existingContent.trimEnd()
            return if (trimmed.isEmpty()) {
                managedBlock
            } else {
                "$trimmed\n\n$managedBlock"
            }
        }
    }

    fun syncGitignore(notesDir: String, extensions: List<String>): Result<Unit> {
        return try {
            val dir = File(notesDir)
            if (!dir.exists() || !dir.isDirectory) {
                return Result.failure(IllegalArgumentException("Notes directory does not exist: $notesDir"))
            }

            val gitignoreFile = File(dir, ".gitignore")
            val existing = if (gitignoreFile.exists()) gitignoreFile.readText() else ""
            val updated = updateGitignoreContent(existing, extensions)

            if (existing != updated) {
                gitignoreFile.writeText(updated)
            }
            Result.success(Unit)
        } catch (e: Exception) {
            Result.failure(e)
        }
    }
}

